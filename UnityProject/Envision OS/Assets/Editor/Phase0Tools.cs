using System;
using System.IO;
using EnvisionOS;
using TMPro;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.TextCore.LowLevel;

public static class Phase0Tools
{
    public const string ScenePath = "Assets/Scenes/Launcher.unity";
    [MenuItem("Envision OS/Phase 0/1 Create Launcher %&l")]
    public static void CreateLauncher()
    {
        if (File.Exists(ScenePath)) { Debug.LogWarning("Launcher already exists; preserving it."); return; }
        if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;
        if (Shader.Find("TextMeshPro/Distance Field") == null)
        {
            TMP_PackageResourceImporter.ImportResources(true, false, false);
            Debug.Log("[Phase0] Importing TMP essentials. Run Create Launcher again after import completes.");
            return;
        }
        var font = AssetDatabase.LoadAssetAtPath<Font>("Assets/Art/Fonts/NotoSansCJKsc-Regular.otf");
        if (font == null) throw new InvalidOperationException("Install the licensed Noto font before generating Launcher.");
        var tmp = TMP_FontAsset.CreateFontAsset(font, 64, 6, GlyphRenderMode.SDFAA, 2048, 2048, AtlasPopulationMode.Dynamic, true);
        tmp.name = "Envision Chinese SDF";
        AssetDatabase.CreateAsset(tmp, "Assets/Art/Fonts/Envision Chinese SDF.asset");
        AssetDatabase.AddObjectToAsset(tmp.material, tmp);
        AssetDatabase.AddObjectToAsset(tmp.atlasTextures[0], tmp);
        AssetDatabase.SaveAssets();
        EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        var camera = new GameObject("Main Camera", typeof(Camera));
        camera.tag = "MainCamera"; camera.GetComponent<Camera>().clearFlags = CameraClearFlags.SolidColor;
        camera.GetComponent<Camera>().backgroundColor = new Color(.063f,.078f,.106f); camera.GetComponent<Camera>().cullingMask = 0;
        new GameObject("EventSystem", typeof(EventSystem), typeof(StandaloneInputModule));
        new GameObject("Dashboard", typeof(DashboardController)).GetComponent<DashboardController>().font = tmp;
        Configure();
        EditorSceneManager.SaveScene(EditorSceneManager.GetActiveScene(), ScenePath);
        EditorBuildSettings.scenes = new[] { new EditorBuildSettingsScene(ScenePath, true) };
        AssetDatabase.SaveAssets();
        Debug.Log("[Phase0] Launcher generated by Unity Editor. Enter Play Mode to preview UI.");
    }
    private static void Configure()
    {
        PlayerSettings.companyName = "EnvisionOS"; PlayerSettings.productName = "Envision OS";
        PlayerSettings.bundleVersion = "0.1.0";
        PlayerSettings.SetApplicationIdentifier(BuildTargetGroup.Android, "com.envisionos.launcher");
        PlayerSettings.defaultInterfaceOrientation = UIOrientation.LandscapeLeft;
        PlayerSettings.defaultScreenWidth = 1920; PlayerSettings.defaultScreenHeight = 1080;
        PlayerSettings.Android.minSdkVersion = AndroidSdkVersions.AndroidApiLevel23;
        PlayerSettings.Android.targetSdkVersion = AndroidSdkVersions.AndroidApiLevelAuto;
        PlayerSettings.SetScriptingBackend(BuildTargetGroup.Android, ScriptingImplementation.IL2CPP);
        PlayerSettings.Android.targetArchitectures = AndroidArchitecture.ARMv7 | AndroidArchitecture.ARM64;
        PlayerSettings.Android.useCustomKeystore = false;
    }
    [MenuItem("Envision OS/Phase 0/2 Build Debug APK %#k")]
    public static void BuildAndroid()
    {
        if (!File.Exists(ScenePath)) throw new InvalidOperationException("Create Launcher first.");
        Configure();
        if (!EditorUserBuildSettings.SwitchActiveBuildTarget(BuildTargetGroup.Android, BuildTarget.Android)) throw new InvalidOperationException("Android target switch failed.");
        EditorUserBuildSettings.buildAppBundle = false;
        Directory.CreateDirectory("Builds/Android");
        var report = BuildPipeline.BuildPlayer(new[] { ScenePath }, "Builds/Android/EnvisionOS-Phase0-debug.apk", BuildTarget.Android, BuildOptions.Development);
        var summary = report.summary;
        var result = $"Result: {summary.result}\nErrors: {summary.totalErrors}\nWarnings: {summary.totalWarnings}\nBytes: {summary.totalSize}\nDuration: {summary.totalTime}\nOutput: {summary.outputPath}\nUnity: {Application.unityVersion}\n";
        File.WriteAllText("Builds/Android/build-result.txt", result);
        Debug.Log("[Phase0 APK] " + result);
        if (summary.result != BuildResult.Succeeded) throw new InvalidOperationException("APK build failed; inspect Console and Editor.log.");
    }
}
